import AVFoundation
import Foundation

enum Meow: String, CaseIterable {
    case move, capture, check, checkmate, castle, blunder, mistake, inaccuracy, best, correct, wrong
}

enum SoundPack: String, CaseIterable, Identifiable {
    case soft, chirps, purrs
    var id: String { rawValue }
    var label: String {
        switch self {
        case .soft: return "Soft mews"
        case .chirps: return "Chirps & trills"
        case .purrs: return "Purrs & pops"
        }
    }
    var detail: String {
        switch self {
        case .soft: return "Rounded mews, tiny move sounds, a happy rising finish."
        case .chirps: return "Bright little chirps and rolling, musical trills."
        case .purrs: return "Quiet paw pops, warm purrs and airy warning puffs."
        }
    }
}

/// Plays the cat sound effects in `Sounds/` (generated by scripts/make_sounds.py).
@MainActor
final class SoundPlayer {
    static let shared = SoundPlayer()

    private var players: [String: AVAudioPlayer] = [:]
    private var sampleTask: Task<Void, Never>?

    var enabled: Bool { UserDefaults.standard.object(forKey: "soundOn") as? Bool ?? true }

    private init() {
        // .ambient respects the silent switch and mixes with other audio.
        try? AVAudioSession.sharedInstance().setCategory(.ambient, options: [.mixWithOthers])
        for pack in SoundPack.allCases {
          for m in Meow.allCases {
            let name = "\(pack.rawValue)_\(m.rawValue)"
            if let url = Bundle.main.url(forResource: name, withExtension: "wav"),
               let p = try? AVAudioPlayer(contentsOf: url) {
                p.prepareToPlay()
                players[name] = p
            }
          }
        }
    }

    func play(_ m: Meow) {
        sampleTask?.cancel()
        let pack = SoundPack(rawValue: UserDefaults.standard.string(forKey: "soundPack") ?? "") ?? .soft
        play(m, pack: pack)
    }

    private func play(_ m: Meow, pack: SoundPack) {
        guard enabled, let p = players["\(pack.rawValue)_\(m.rawValue)"] else { return }
        p.currentTime = 0
        p.play()
    }

    /// Same event sequence for each pack so the owner can compare them fairly.
    func sample(_ pack: SoundPack) {
        sampleTask?.cancel()
        players.values.forEach { $0.stop() }
        sampleTask = Task {
            for event in [Meow.move, .capture, .check, .blunder, .correct] {
                guard !Task.isCancelled else { return }
                play(event, pack: pack)
                do { try await Task.sleep(for: .milliseconds(650)) } catch { return }
            }
        }
    }

    /// Picks the most important sound for a reviewed move.
    func play(for move: MoveReview) {
        play(Self.meow(for: move))
    }

    static func meow(for m: MoveReview) -> Meow {
        if m.san.hasSuffix("#") { return .checkmate }
        switch m.grade {
        case .blunder: return .blunder
        case .mistake: return .mistake
        default: break
        }
        if m.san.hasSuffix("+") { return .check }
        if m.san.contains("x") { return .capture }
        if m.san.hasPrefix("O-O") { return .castle }
        if m.grade == .inaccuracy { return .inaccuracy }
        if m.grade == .best && (m.tags.contains("found_fork") || m.headline.contains("takes")) { return .best }
        return .move
    }
}
